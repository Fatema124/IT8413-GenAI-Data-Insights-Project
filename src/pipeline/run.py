"""Run the whole data pipeline: raw files -> checked, prepared tables.

    python -m src.pipeline.run            # uses data/raw/, writes data/processed/
    python -m src.pipeline.run --no-d3    # if the iGA XLSX is not available yet

Outputs (all regenerated on every run; data/processed/ is git-ignored):
    cpi_long.csv          one row per month x category x population
    weights.csv           Table 2.01 expenditure weights
    labels.csv            code -> canonical name, level, coverage, weight
    quality_report.csv    every check, what it found and what was changed
    quality_report.md     the same, readable (paste into the report)
"""
from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import pandas as pd

from . import config, load, prepare


@dataclass
class PreparedData:
    cpi: pd.DataFrame            # tidy table (F1 output)
    weights: pd.DataFrame | None
    labels: pd.DataFrame
    quality: pd.DataFrame


def build(raw_dir: Path | None = None, use_d3: bool = True) -> PreparedData:
    raw_dir = Path(raw_dir or config.RAW_DIR)
    log = prepare.QualityLog()

    d1 = prepare.prepare_d1(load.load_d1(raw_dir / config.RAW_FILES["D1"]), log)
    d2 = prepare.prepare_d2(load.load_d2(raw_dir / config.RAW_FILES["D2"]), log)

    weights = history = None
    d3_path = raw_dir / config.RAW_FILES["D3"]
    if use_d3 and d3_path.exists():
        raw_w, raw_h, raw_idx = load.load_d3(d3_path)
        weights = prepare.prepare_weights(raw_w, log)
        history = prepare.prepare_history(raw_h, d1, log)
        prepare.crosscheck_table_201(raw_idx, d1, log)
    else:
        log.add("D3", "Dataset 3 loaded", "no", f"{d3_path.name} not found - weights unavailable", "warning")

    cpi = prepare.build_cpi_table(d1, d2, history, log)
    if weights is not None:
        prepare.weighted_headline_check(cpi, weights, log)
    log.add("All", "Prepared rows", len(cpi),
            ", ".join(f"{k}: {v}" for k, v in cpi.groupby("source").size().items()))
    return PreparedData(cpi, weights, prepare.labels_table(cpi, weights), log.to_frame())


def write_outputs(data: PreparedData, out_dir: Path | None = None) -> Path:
    out = Path(out_dir or config.PROCESSED_DIR)
    out.mkdir(parents=True, exist_ok=True)
    data.cpi.to_csv(out / "cpi_long.csv", index=False, date_format="%Y-%m")
    data.labels.to_csv(out / "labels.csv", index=False, date_format="%Y-%m")
    if data.weights is not None:
        data.weights.to_csv(out / "weights.csv", index=False)
    data.quality.to_csv(out / "quality_report.csv", index=False)
    (out / "quality_report.md").write_text(quality_markdown(data.quality), encoding="utf-8")
    (out / "manifest.json").write_text(json.dumps({
        "built_at": datetime.now().isoformat(timespec="seconds"),
        "sources": {k: {"file": config.RAW_FILES[k], **v} for k, v in config.SOURCES.items()},
        "rows": {"cpi_long": len(data.cpi),
                 "weights": 0 if data.weights is None else len(data.weights)},
    }, indent=2), encoding="utf-8")
    return out


def quality_markdown(q: pd.DataFrame) -> str:
    icon = {"ok": "OK", "fixed": "FIXED", "warning": "CHECK", "info": "INFO"}
    lines = ["# Data preparation report (F1)", "",
             "Generated by `python -m src.pipeline.run`. Each row is a check made in code.", "",
             "| Source | Check | Result | Detail | Status |", "|---|---|---|---|---|"]
    for r in q.itertuples():
        detail = str(r.detail).replace("|", "/")
        lines.append(f"| {r.source} | {r.check} | {r.result} | {detail} | {icon.get(r.status, r.status)} |")
    return "\n".join(lines) + "\n"


def load_prepared(processed_dir: Path | None = None) -> PreparedData:
    """Fast path for the app: read the processed CSVs (run the pipeline first)."""
    d = Path(processed_dir or config.PROCESSED_DIR)
    if not (d / "cpi_long.csv").exists():
        raise FileNotFoundError("Run `python -m src.pipeline.run` first to build data/processed/.")
    cpi = pd.read_csv(d / "cpi_long.csv", dtype={"code": str, "division": str})
    cpi["period"] = pd.to_datetime(cpi["period"], format="%Y-%m")
    w_path = d / "weights.csv"
    weights = pd.read_csv(w_path, dtype={"code": str, "division": str}) if w_path.exists() else None
    labels = pd.read_csv(d / "labels.csv", dtype={"code": str, "division": str})
    quality = pd.read_csv(d / "quality_report.csv")
    return PreparedData(cpi, weights, labels, quality)


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw", type=Path, default=None)
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--no-d3", action="store_true")
    args = ap.parse_args(argv)
    data = build(args.raw, use_d3=not args.no_d3)
    out = write_outputs(data, args.out)
    print(data.quality.to_string(index=False, max_colwidth=70))
    print(f"\nWrote prepared data to {out}")
    flagged = data.quality[data.quality["status"] == "warning"]
    if len(flagged):
        print(f"{len(flagged)} check(s) need a look - see quality_report.md")


if __name__ == "__main__":
    main()
