"""Write docs/sources.md, the sources record for the datasets and documents (brief deliverable 6.2).

    python -m scripts.write_sources

Everything comes from src/pipeline/config.py, so the record always matches what
the app shows. Run it again after changing a date or a source in config.py.
"""
from __future__ import annotations

from src.pipeline import config

OUT = config.REPO_ROOT / "docs" / "sources.md"


def _date(iso: str) -> str:
    y, m, d = iso.split("-")
    return f"{d}/{m}/{y}"


def render() -> str:
    lines = [
        "# Sources: datasets and documents",
        "",
        "Generated by `python -m scripts.write_sources` from `src/pipeline/config.py`.",
        "",
        "## Datasets",
        "",
        "| # | Title | Publisher | Link | File in the project | Retrieved | Rows used | Terms |",
        "|---|---|---|---|---|---|---|---|",
    ]
    rows_used = {"D1": "8,004 (Jan 2017 - Aug 2026)", "D2": "2,288 (May 2019 - Aug 2026)",
                 "D3": "Tables 1 (2011-2016 + 2011 % changes), 2.01; Tables 2.02, 2.03, 3 for checks"}
    for k, v in config.SOURCES.items():
        terms = f"[{v['licence']}]({v['licence_url']})" if v.get("licence_url") else v["licence"]
        lines.append(f"| {k[1]} | {v['title']} | {v['publisher']} | [link]({v['url']}) | "
                     f"`data/raw/{config.RAW_FILES[k]}` | {_date(v['retrieved'])} | {rows_used[k]} | {terms} |")
    lines += [
        "",
        "## Versions",
        "",
        f"- **Datasets 1-2.** Retrieved on {_date(config.D12_RETRIEVED)} (proposal Section 2). The committed "
        f"files also hold September 2026 (8,073 and 2,314 rows); the pipeline drops the months after "
        f"{config.DATA_END}, which leaves exactly the proposal's 8,004 and 2,288 rows.",
        f"- **Dataset 3.** Not stored in the repository (iGA Terms of Use). Direct file: "
        f"[{config.RAW_FILES['D3']}]({config.D3_DOWNLOAD_URL}). SHA-256 of the group's copy: "
        f"`{config.D3_SHA256}`. `python -m scripts.download_sources` downloads it and compares the fingerprint.",
        "",
        "## Statement shown with the data (licence clause 3.3)",
        "",
        f"> {config.ATTRIBUTION}",
        ">",
        f"> {config.OWN_ANALYSIS_NOTE}",
        "",
        "## Documents",
        "",
        "Used for questions over the documents (F5), as approved in the proposal. Per the terms below, "
        "the files are not committed to the public repository.",
        "",
        "| # | Title | Publisher | Link | Retrieved | Terms |",
        "|---|---|---|---|---|---|",
    ]
    for doc in config.DOCUMENTS:
        url = doc["url"].split(" ", 1)
        link = f"[link]({url[0]})" + (f" {url[1]}" if len(url) > 1 else "")
        lines.append(f"| {doc['n']} | {doc['title']} | {doc['publisher']} | {link} | {_date(doc['retrieved'])} | "
                     f"[{doc['terms']}]({doc['terms_url']}) |")
    lines += [
        "",
        "**What the terms allow.** Datasets 1-2: copying, adapting and using the data in applications, with the "
        "statement above and the extraction date (licence clause 3). Dataset 3 and documents 4-10: iGA's and "
        "MOIC's website terms do not allow republishing without written permission, so these files are used "
        "only inside the tool, with citation, and are not committed to the repository.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    OUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
